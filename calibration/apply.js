// Turns calibration/fit.json into the game's crowd settings: site/js/engine/calibrated.js.
//   node calibration/apply.js
//
// Personas: each weekday's crowd is modelled on one real 2/3-game crowd, shallow on Monday to deep on
// Sunday (the hardest day). Its fitted τ, noise, exact share, theorists, jokers and imagined-crowd size
// are the day's base settings; dailySettings jitters them with the date seed.
//
// Families: other question types are adapted from the persona using how the same YouTube viewers played
// them. Depth (τ) scales by the ratio to their 2/3-game τ, since depth is what differs between crowds;
// the theorist and joker shares, noise, exact share and imagined-crowd size are the family's own fitted
// values (ratios of small shares blow up on deep personas).
//
// Changing calibrated.js changes future crowds: regenerate only future days (see CLAUDE.md).

import { readFileSync, writeFileSync } from 'node:fs';

const PERSONA_BY_WEEKDAY = ['ft', 'rubinstein2007', 'politiken2005', 'nyt2015', 'expansion', 'waitbutwhy2015', 'spektrum'];
const LABELS = {
  ft: 'Financial Times readers (1997)',
  rubinstein2007: 'students in 66 game theory courses (Rubinstein 2007)',
  politiken2005: 'Politiken readers (2005)',
  nyt2015: 'New York Times readers (2015)',
  expansion: 'Expansión readers (1997)',
  waitbutwhy2015: 'Wait But Why readers (2015)',
  spektrum: 'Spektrum der Wissenschaft readers (1997)',
};
const ANCHOR = 'yt_two_thirds';
const FAMILY_FITS = {
  beautyUp: 'yt_plus_five', avoid: 'yt_avoid_rank', underbid: 'yt_underbid', threshold: 'yt_threshold',
  commonMost: 'yt_common_most', commonLeast: 'yt_common_least', catch: 'yt_catch', splitsteal: 'yt_splitsteal',
  selfref: 'yt_selfref', tank: 'yt_tank',
};

const r3 = (x) => Math.round(x * 1000) / 1000;
const fits = JSON.parse(readFileSync(new URL('./fit.json', import.meta.url), 'utf8')).datasets;

const personas = {};
for (const id of new Set(PERSONA_BY_WEEKDAY)) {
  const f = fits[id];
  if (!f) throw new Error(`no fit for persona ${id}; run node calibration/fit.js`);
  const { tau, noise, exact, eq, joker, sample } = f.settings;
  personas[id] = { label: LABELS[id], tau, noise, exact, eq, joker, sample, mean: r3(f.metrics.modelMean) };
}

const anchor = fits[ANCHOR]?.settings;
if (!anchor) throw new Error(`no fit for ${ANCHOR} (the private YouTube data): cannot derive family scaling`);
const family = { beauty: {} };
for (const [name, id] of Object.entries(FAMILY_FITS)) {
  const s = fits[id].settings;
  family[name] = {
    tau: r3(s.tau / anchor.tau),
    eq: s.eq,
    joker: s.joker,
    noise: s.noise,
    exact: s.exact,
    sample: s.sample,
  };
}

const out = `// Generated by calibration/apply.js from calibration/fit.json (fitted ${JSON.parse(readFileSync(new URL('./fit.json', import.meta.url), 'utf8')).generated}).
// Do not edit by hand: refit, then rerun the script. See docs/calibration.md.

/** Real crowds the daily bots are modelled on, with their fitted settings and 2/3-game mean. */
export const PERSONAS = ${JSON.stringify(personas, null, 2)};

/** Persona for each UTC weekday (0 = Sunday, the deepest crowd and hardest day). */
export const PERSONA_BY_WEEKDAY = ${JSON.stringify(PERSONA_BY_WEEKDAY)};

/** Per family: tau multiplies the persona's; eq, joker, noise, exact, sample replace it. */
export const FAMILY = ${JSON.stringify(family, null, 2)};
`;
writeFileSync(new URL('../site/js/engine/calibrated.js', import.meta.url), out);
console.log(out);
