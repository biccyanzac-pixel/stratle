"""Writes docs/calibration.md from calibration/fit.json, the datasets and calibrated.js.

Usage (from the repo root): python -I calibration/tools/report.py
YouTube rows show settings and fit metrics only; their plots stay in calibration/private/plots.
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def load(*parts):
    with open(os.path.join(ROOT, *parts), encoding="utf-8") as fh:
        return json.load(fh)


def calibrated():
    src = open(os.path.join(ROOT, "site", "js", "engine", "calibrated.js"), encoding="utf-8").read()
    grab = lambda name: json.loads(re.search(rf"export const {name} = (.*?);\n", src, re.S).group(1))  # noqa: E731
    return grab("PERSONAS"), grab("PERSONA_BY_WEEKDAY"), grab("FAMILY")


def game(d):
    p = d["params"]
    if d["template"] == "target":
        a = p["a"]
        rule = "average" if a == [1, 1] else f"{a[0]}/{a[1]} of the average"
        return f"{rule}{' + ' + str(p['b']) if p['b'] > 0 else ''}, 0–{p['range']}"
    if d["template"] == "avoid":
        return f"percentile rings, 0–{p['range']}"
    return f"bid 1–{p['max']} under the average"


def main():
    fits = load("calibration", "fit.json")
    published = load("calibration", "datasets", "published.json")
    personas, by_weekday, family = calibrated()
    f = fits["datasets"]
    L = []
    w = L.append

    w("# Calibration\n")
    w(f"_Generated by `calibration/tools/report.py` from the fit of {fits['generated']}. Do not edit by hand._\n")
    w("The simulated crowd is fitted to real answers to the same games. This page lists the sources, how well the "
      "model reproduces each one, and how the fits become the daily crowd settings.\n")

    w("## The model being fitted\n")
    w("Each simulated crowd is a mix of:\n")
    w("- **Thinkers, levels 0–4** in Poisson(τ) proportions, truncated at 4. Level 0 plays the template's naive answer "
      "(uniform, or high bids in the bid game). Level k best-responds to levels 0..k−1. Its answers are a share `exact` "
      "on the best answer plus a Gaussian with sd = `noise` × range.")
    w("- **Imagined crowd size (`sample`)**: bots judge each answer against 128 imagined crowds of `sample` players "
      "drawn from their belief (payoff sampling, after Osborne & Rubinstein). Small samples mean doubt, which makes "
      "cliff-edge answers risky. This is what pulls bids down to 3–5 in the bid game. ∞ means the bots know the crowd exactly.")
    w("- **Theorists (`eq`)**: bots who play the game's equilibrium (0 or 1 in the 2/3 game, 100 in \"average + 5\", "
      "a bid of 1). Every real 2/3 game has this spike; the depth cap at level 4 cannot produce it.")
    w("- **Jokers (`joker`)**: meme answers such as 0, 100, 69, 42 and 50.\n")
    w("**Loss** = W1 + 20·TV + 10·TV1 + mean error. W1 is the earth-mover distance between the cumulative "
      "distributions, in % of the range. TV is the share of answers in the wrong place on 5%-wide bins, and TV1 the same "
      "on single numbers (0–100 games only, so the spikes count). The mean error, also in % of the range, is measured "
      "against the *reported* mean. Settings are grid-searched, with a finer τ pass at the end. Datasets that only report "
      "a mean fit τ alone and borrow the other settings (the median of the published full-histogram fits).\n")

    w("## Sources\n")
    w("| Dataset | n | Game | Data used | Source | Terms |")
    w("| --- | --- | --- | --- | --- | --- |")
    for d in published:
        kind = "histogram (digitised)" if d["id"] in ("ft", "spektrum", "expansion", "nyt2015") else \
            "histogram (raw)" if "freq" in d else "bins" if "bins" in d else "mean only"
        terms = d["source"]["terms"].replace("|", "/")
        w(f"| {d['label']} | {d['n']:,} | {game(d)} | {kind} | [link]({d['source']['url']}) | {terms} |")
    w("| YouTube survey (owner-provided) | 3,190–3,206 per question | 2/3, average + 5, percentile rings 0–1000, "
      "bid 1–20 | raw answers | [video](https://www.youtube.com/watch?v=sJ7IHSTOzng) | Calibration only. "
      "Data and derived histograms are kept in git-ignored `calibration/private/`. |\n")
    w("Notes on individual sources:\n")
    for d in published:
        if d["source"].get("note"):
            w(f"- **{d['label']}**: {d['source']['note']}")
    w("- **Not found online**: the original Politiken article and data, Nagel's raw lab choices, the NYT raw responses "
      "and the ChessBase histogram. These are used through their published summaries only.\n")

    w("## Fit quality\n")
    w("| Dataset | τ | noise | exact | theorists | jokers | imagined crowd | model mean | real mean | W1 % | TV | TV1 |")
    w("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |")
    order = [d["id"] for d in published] + sorted(k for k in f if k.startswith("yt_"))
    for k in order:
        r = f[k]
        s, m = r["settings"], dict(r["metrics"])
        if r.get("parts"):
            # Several questions fitted jointly: average their metrics; means are meaningless for options.
            for key in ("w1", "tv", "tv1"):
                vals = [p["metrics"][key] for p in r["parts"] if key in p["metrics"]]
                if vals:
                    m[key] = sum(vals) / len(vals)
                else:
                    m.pop(key, None)
            m.pop("modelMean", None)
        cell = lambda key, fmt="{:.2f}": fmt.format(m[key]) if key in m else "–"  # noqa: E731
        w(f"| {r['label']} | {s['tau']:.2f} | {s['noise']} | {s['exact']} | {s['eq']:.0%} | {s['joker']:.0%} | "
          f"{s['sample'] or '∞'} | {cell('modelMean')} | {'private' if r.get('private') else r['reported'].get('mean', '–')} | {cell('w1')} | "
          f"{cell('tv')} | {cell('tv1')} |")
    w("")
    w("For choice games (threshold, most/least common, catch, split or steal), TV is the share of answers on the wrong "
      "option, averaged over the questions fitted together. For the YES/NO question it is on the vote.\n")
    w("Reading the table: a W1 of 1% on a 0–100 game means the simulated answers sit about 1 point away from the "
      "real ones on average. A TV of 0.10 means 10% of the answers fall in the wrong 5-point bin.\n")

    w("## Overlays (published sources)\n")
    for d in published:
        if os.path.exists(os.path.join(ROOT, "docs", "img", "calibration", f"{d['id']}.png")):
            w(f"![{d['label']}](img/calibration/{d['id']}.png)\n")
    w("The YouTube overlays are in `calibration/private/plots/` and are not published.\n")

    w("## From fits to the daily crowd\n")
    w("**Personas.** Each weekday's crowd is modelled on one real crowd's fit. They are ordered by how low that crowd's "
      "2/3-game mean is, from Monday (36) to Sunday (19, the hardest day, per the house rules). τ alone is not ordered, "
      "because theorists and doubt also lower the mean. The date seed jitters τ by ±10%, noise by ±15%, and the theorist and joker "
      "shares by ±25%.\n")
    w("| Day | Persona | τ | theorists | jokers | 2/3-game mean |")
    w("| --- | --- | --- | --- | --- | --- |")
    days = ["Sunday", "Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday"]
    for i in [1, 2, 3, 4, 5, 6, 0]:
        p = personas[by_weekday[i]]
        w(f"| {days[i]} | {p['label']} | {p['tau']:.2f} | {p['eq']:.0%} | {p['joker']:.0%} | {p['mean']:.1f} |")
    w("")
    w("**Families.** The same YouTube viewers answered every question type, so their fits show how differently "
      "people play each kind of game. τ scales by the family's ratio to their 2/3-game τ. The theorist and joker shares, "
      "noise, exact share and imagined-crowd size are the family's own fitted values.\n")
    w("| Family | τ × | theorists | jokers | noise | exact | imagined crowd | Fitted on |")
    w("| --- | --- | --- | --- | --- | --- | --- | --- |")
    src = {"beautyUp": "average + 5", "avoid": "percentile rings 0–1000", "underbid": "bid under the average",
           "threshold": "2 threshold questions", "commonMost": "most common number, colour", "commonLeast": "least common letter, A–D",
           "catch": "2 points-with-a-catch questions", "splitsteal": "split or steal, two neighbours", "selfref": "\"more NO than YES?\" vote",
           "tank": "German tank, max 318"}
    w("| beauty (2/3-style, unravels down) | 1 | persona | persona | persona | persona | persona | the personas |")
    for name, v in family.items():
        if name == "beauty":
            continue
        w(f"| {name} | {v['tau']} | {v['eq']:.0%} | {v['joker']:.0%} | {v['noise']} | {v['exact']} | {v['sample'] or '∞'} | {src[name]} |")
    w("")

    w("## What the fits say, and their limits\n")
    w("- **Crowds differ a lot in depth.** Students and lab subjects fit τ ≈ 1–1.6. Large newspaper and online "
      "crowds fit τ ≈ 1.3–3. Self-selected readers of the FT, Spektrum and Wait But Why fit τ ≈ 3.8–4.6, with 16–20% "
      "theorists. This is wider than the 1.1–2.0 first assumed, because theorists and doubt now carry part of what τ "
      "used to explain.")
    w("- **τ is not cleanly identified.** It trades off against the theorist share, noise and imagined-crowd size: "
      "several settings fit nearly as well. The personas use each dataset's best joint fit. Treat individual "
      "parameters as descriptive, not as measurements.")
    w("- **The 1997 newspaper histograms are digitised from the paper's figure.** Bins of one or two entries are under "
      "a pixel, so the digitised means are 0.3–3 points off the reported ones. The loss uses the reported mean, which "
      "is exact.")
    w("- **Weakest fits**: the bid game (the model peaks at 6, while real bids are flat from 1 to 5) and Rubinstein's "
      "students, who have a 16% spike at 50 and 20% above 50 (\"misunderstood the game\", in Rubinstein's words). "
      "The model covers that spike with jokers.")
    w("- **Upward rules are played shallower.** In \"average + 5\" the same viewers fit τ ≈ 1.1 against 2.2 in the 2/3 "
      "game, so upward rules are their own family (`beautyUp`).")
    w("- **Choice games are mostly shallow.** In the most/least common, split-or-steal and YES/NO questions the crowd is "
      "close to naive salience plus noise (τ × 0.05–0.2). Threshold options and points-with-a-catch show real "
      "thinking (τ × 0.9–1.4) and fit well (TV 5–9%).")
    w("- **Weakly identified families.** Split or steal and the YES/NO question each have one free number (the split "
      "share, the YES share), so they fit exactly with τ at the bottom of the grid. Their depth is a guess that the "
      "Phase 5 recalibration from real players should replace.")
    w("- **Most common is the weakest choice fit** (TV ≈ 0.16). Real people pile onto 7 *and* 1 in \"most common "
      "number\"; the salience prior (7, 1 and the top number as focal points) still under-predicts 1. Level 0's "
      "salience priors are hand-set, not fitted.")
    w("- **The German tank crowd** is the largest-max-seen plus a Bayesian guess, with a large joker share (capped "
      "at 30% in the game) for round-ups such as 350, 400 and 500, and double-the-average. It fits closely (W1 ≈ 1%).")
    w("- **Not calibrated**: the YouTube group split-or-steal (halves voting as blocs) and the meta questions. No "
      "template plays those.\n")

    w("## Reproduce\n")
    w("```")
    w("python -I calibration/tools/digitise_bosch.py calibration/raw/bosch2002/fig_p4.png calibration/raw/bosch2002/digitised_fig1.json")
    w("python -I calibration/tools/digitise_nyt.py calibration/raw/nyt2015/wbw_nyt_graph.png calibration/raw/nyt2015/digitised.json")
    w("python -I calibration/tools/build_datasets.py   # needs calibration/raw and calibration/private")
    w("node calibration/fit.js                           # ~25 min; or pass dataset ids")
    w("node calibration/apply.js                         # writes site/js/engine/calibrated.js")
    w("node scripts/generate.js --regenerate-future      # rewrites future day files only")
    w("python -I calibration/tools/plot_fits.py")
    w("python -I calibration/tools/report.py")
    w("```\n")
    w("The downloads (`calibration/raw/`) are not committed: the source URLs above re-fetch them. Changing "
      "`calibrated.js` changes future crowds, so after a refit run `node scripts/generate.js --regenerate-future`: it rewrites only days after today and refuses if a published day would change.")

    with open(os.path.join(ROOT, "docs", "calibration.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(L) + "\n")
    print("wrote docs/calibration.md")


if __name__ == "__main__":
    main()
